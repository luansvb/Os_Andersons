import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

export const PHONE_WIDTH=390;
export const PHONE_QUERY='(min-width:761px) and (pointer:coarse) and (hover:none) and (max-aspect-ratio:2/3)';
export const PHONE_STYLES={
 main:['styles.css','credits.css'],
 lt32:['lt32.css'],
 activation:['activation.css'],
 heist:['heist.css','screen-driving.css'],
 recovery:['recovery.css','screen-driving.css','credits.css']
};

// Some mobile browsers request a desktop viewport. Keep the same phone layout
// and physical text size there, without changing normal desktop CSS or zoom.
function rules(css){
 const out=[];let start=0,open=-1,depth=0,quote='';
 for(let i=0;i<css.length;i++){
  const c=css[i];
  if(quote){if(c==='\\')i++;else if(c===quote)quote='';continue;}
  if(c==='"'||c==="'"){quote=c;continue;}
  if(c==='{'){if(depth++===0)open=i;}
  else if(c==='}'&&--depth===0){out.push([css.slice(start,open).trim(),css.slice(open+1,i)]);start=i+1;}
  else if(c===';'&&depth===0){start=i+1;}
 }
 if(depth!==0||quote)throw new Error('Unbalanced CSS in mobile build');
 return out;
}
function remValues(body){
 return body.replace(/("(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*')|(-?(?:\d*\.)?\d+)px\b/g,(all,quoted,n)=>quoted||`${Number((Number(n)/16).toFixed(6))}rem`);
}
function phoneMedia(query){
 const branches=query.split(',').map(branch=>{
  let matches=true;
  const rest=branch.replace(/\((min|max)-(width|height)\s*:\s*([\d.]+)px\)/g,(_,bound,axis,n)=>{
   const size=axis==='width'?PHONE_WIDTH:844;
   if(bound==='min'?size<Number(n):size>Number(n))matches=false;
   return '';
  }).replace(/^\s*(?:only\s+)?screen\b/,'').replace(/^\s*and\s*|\s*and\s*$/g,'').replace(/\s+and\s+(?=and\b)/g,' ').trim();
  return matches?rest:null;
 }).filter(x=>x!==null);
 if(!branches.length)return null;
 if(branches.includes(''))return '';
 return branches.join(',');
}
export function compilePhoneCss(css){
 return rules(css.replace(/\/\*[\s\S]*?\*\//g,'')).map(([head,body])=>{
  if(head.startsWith('@media')){
   const query=phoneMedia(head.slice(6).trim());
   if(query===null)return '';
   const content=compilePhoneCss(body);
   return query?`@media ${query}{${content}}`:content;
  }
  if(/^@(supports|layer|container)\b/.test(head))return `${head}{${compilePhoneCss(body)}}`;
  return `${head}{${remValues(body)}}`;
 }).join('\n');
}
export async function buildMobile(root=fileURLToPath(new URL('../dist/',import.meta.url))){
 for(const [entry,sources] of Object.entries(PHONE_STYLES)){
  const css=(await Promise.all(sources.map(name=>readFile(resolve(root,name),'utf8')))).join('\n');
  const header=`/* Generated by scripts/build-mobile.mjs. Edit the source stylesheets. */\n@media ${PHONE_QUERY}{\n`;
  await writeFile(resolve(root,`phone-${entry}.css`),header+compilePhoneCss(css)+`\nhtml{font-size:${16/PHONE_WIDTH*100}vw;--phone-ui:1}\n}\n`);
 }
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))await buildMobile();
